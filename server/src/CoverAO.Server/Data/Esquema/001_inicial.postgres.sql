-- CoverAO: el esquema de la base, versión 1, en Postgres. Es la misma que 001_inicial.sqlite.sql, tabla por tabla y
-- columna por columna (lo cuida un test), con los tipos de Postgres: fechas en timestamptz, booleanos en boolean, la IP en
-- inet, los id como identidad.
--
-- LAS RESTRICCIONES SON LAS DEL TIPO DEL MODELO, no reglas de juego. Un byte del servidor es un smallint con un CHECK entre
-- 0 y 255; un short, un smallint; un int, un integer; un long, un bigint. La base no acepta nada que el servidor no pueda
-- cargar, y tampoco rechaza nada que el juego produzca: un guardado rechazado es una partida perdida.
--
-- El clan y la pareja van por NOMBRE, como en el .chr, y los amigos también.

CREATE TABLE cuentas (
    id                 bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             text        NOT NULL CHECK (char_length(nombre) BETWEEN 1 AND 20),
    clave_hash         text        NOT NULL,             -- pbkdf2$... (o el SHA-256 viejo hasta el próximo ingreso)
    clave_sal          text        NOT NULL DEFAULT '',  -- sólo la del SHA-256 viejo
    codigo_hash        text        NOT NULL DEFAULT '',  -- el código de recuperación (UserCodigo)
    baneada            boolean     NOT NULL DEFAULT false,
    es_bot             boolean     NOT NULL DEFAULT false,
    trampas            integer     NOT NULL DEFAULT 0,
    donador            boolean     NOT NULL DEFAULT false,
    email              text,                             -- reservado para una web que escriba
    creada_en          timestamptz,                      -- NULL: importada, fecha desconocida
    ultimo_ingreso_en  timestamptz,
    ultima_ip          inet
);
CREATE UNIQUE INDEX cuentas_nombre ON cuentas (upper(nombre));

CREATE TABLE personajes (
    id                    bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id             bigint      NOT NULL REFERENCES cuentas (id) ON DELETE RESTRICT,
    nombre                text        NOT NULL CHECK (char_length(nombre) BETWEEN 1 AND 20),
    creado_en             timestamptz,
    guardado_en           timestamptz,
    borrado_en            timestamptz,                   -- apartado: el nombre queda libre, la fila no se destruye
    conectado_desde       timestamptz,
    -- [INIT]
    genero                smallint    NOT NULL CHECK (genero BETWEEN 0 AND 255),
    raza                  smallint    NOT NULL CHECK (raza BETWEEN 0 AND 255),
    clase                 smallint    NOT NULL CHECK (clase BETWEEN 0 AND 255),
    tierra_natal          smallint    NOT NULL CHECK (tierra_natal BETWEEN 0 AND 255),
    ciudad_hogar          smallint    NOT NULL CHECK (ciudad_hogar BETWEEN 0 AND 255),
    minutos_de_carcel     integer     NOT NULL,
    descripcion           text        NOT NULL,
    rumbo                 smallint    NOT NULL CHECK (rumbo BETWEEN 0 AND 255),
    cabeza                smallint    NOT NULL,
    cuerpo                smallint    NOT NULL,
    anim_arma             smallint    NOT NULL,
    anim_escudo           smallint    NOT NULL,
    anim_casco            smallint    NOT NULL,
    segundos_jugados      bigint      NOT NULL,
    mapa                  smallint    NOT NULL,
    x                     smallint    NOT NULL CHECK (x BETWEEN 0 AND 255),
    y                     smallint    NOT NULL CHECK (y BETWEEN 0 AND 255),
    -- [STATS]
    oro                   integer     NOT NULL,
    oro_en_banco          bigint      NOT NULL,
    vida                  integer     NOT NULL,
    vida_max              integer     NOT NULL,
    energia               integer     NOT NULL,
    energia_max           integer     NOT NULL,
    mana                  integer     NOT NULL,
    mana_max              integer     NOT NULL,
    golpe_min             integer     NOT NULL,
    golpe_max             integer     NOT NULL,
    sed                   smallint    NOT NULL CHECK (sed BETWEEN 0 AND 255),
    sed_max               smallint    NOT NULL CHECK (sed_max BETWEEN 0 AND 255),
    hambre                smallint    NOT NULL CHECK (hambre BETWEEN 0 AND 255),
    hambre_max            smallint    NOT NULL CHECK (hambre_max BETWEEN 0 AND 255),
    skill_pts_libres      smallint    NOT NULL,
    nivel                 smallint    NOT NULL CHECK (nivel BETWEEN 0 AND 255),
    exp                   double precision NOT NULL,
    exp_para_subir        bigint      NOT NULL,
    -- [ATRIBUTOS]
    fuerza                smallint    NOT NULL CHECK (fuerza BETWEEN 0 AND 255),
    agilidad              smallint    NOT NULL CHECK (agilidad BETWEEN 0 AND 255),
    inteligencia          smallint    NOT NULL CHECK (inteligencia BETWEEN 0 AND 255),
    carisma               smallint    NOT NULL CHECK (carisma BETWEEN 0 AND 255),
    constitucion          smallint    NOT NULL CHECK (constitucion BETWEEN 0 AND 255),
    -- [FLAGS]
    privilegios           smallint    NOT NULL CHECK (privilegios BETWEEN 0 AND 255),   -- el civil: el de staff no se guarda
    baneado               boolean     NOT NULL,
    muerto                boolean     NOT NULL,
    navegando             boolean     NOT NULL,
    montando              boolean     NOT NULL,
    veneno                smallint    NOT NULL CHECK (veneno BETWEEN 0 AND 255),
    veces_muerto          integer     NOT NULL,
    -- [FACCIONES] y [MUERTES]
    bando                 smallint    NOT NULL CHECK (bando BETWEEN 0 AND 255),
    rango                 smallint    NOT NULL CHECK (rango BETWEEN 0 AND 255),
    renegados_matados     integer     NOT NULL,
    ciudadanos_matados    integer     NOT NULL,
    republicanos_matados  integer     NOT NULL,
    armada_matados        integer     NOT NULL,
    milicianos_matados    integer     NOT NULL,
    caos_matados          integer     NOT NULL,
    usuarios_matados      integer     NOT NULL,
    criaturas_matadas     integer     NOT NULL,
    -- [CASAMIENTO], [GUILD], [DONADOR], BarcoSlot
    pareja                text        NOT NULL,
    clan                  text        NOT NULL,
    donador               boolean     NOT NULL,
    creditos_donador      bigint      NOT NULL,
    ranura_del_barco      smallint    NOT NULL CHECK (ranura_del_barco BETWEEN 0 AND 255)
);
CREATE UNIQUE INDEX personajes_nombre_vivo ON personajes (upper(nombre)) WHERE borrado_en IS NULL;
CREATE INDEX personajes_cuenta  ON personajes (cuenta_id);
CREATE INDEX personajes_ranking ON personajes (nivel DESC, exp DESC) WHERE borrado_en IS NULL;

-- Las ranuras: una fila por ranura OCUPADA (objeto distinto de 0). Ranura y objeto con el rango del arreglo y del tipo.
CREATE TABLE inventario (
    personaje_id  bigint   NOT NULL REFERENCES personajes (id) ON DELETE CASCADE,
    ranura        smallint NOT NULL CHECK (ranura BETWEEN 1 AND 25),
    objeto        smallint NOT NULL CHECK (objeto <> 0),
    cantidad      smallint NOT NULL,
    equipado      boolean  NOT NULL,
    PRIMARY KEY (personaje_id, ranura)
);
CREATE TABLE boveda (
    personaje_id  bigint   NOT NULL REFERENCES personajes (id) ON DELETE CASCADE,
    ranura        smallint NOT NULL CHECK (ranura BETWEEN 1 AND 40),
    objeto        smallint NOT NULL CHECK (objeto <> 0),
    cantidad      smallint NOT NULL,
    PRIMARY KEY (personaje_id, ranura)
);
CREATE TABLE hechizos (
    personaje_id  bigint   NOT NULL REFERENCES personajes (id) ON DELETE CASCADE,
    ranura        smallint NOT NULL CHECK (ranura BETWEEN 1 AND 35),
    hechizo       smallint NOT NULL CHECK (hechizo <> 0),
    PRIMARY KEY (personaje_id, ranura)
);
CREATE TABLE skills (                              -- las 27, siempre
    personaje_id  bigint   NOT NULL REFERENCES personajes (id) ON DELETE CASCADE,
    skill         smallint NOT NULL CHECK (skill BETWEEN 1 AND 27),
    valor         smallint NOT NULL CHECK (valor BETWEEN 0 AND 255),
    PRIMARY KEY (personaje_id, skill)
);
CREATE TABLE amigos (
    personaje_id  bigint   NOT NULL REFERENCES personajes (id) ON DELETE CASCADE,
    orden         integer  NOT NULL CHECK (orden >= 1),
    nombre        text     NOT NULL,
    PRIMARY KEY (personaje_id, orden)
);
CREATE TABLE penas (
    personaje_id  bigint   NOT NULL REFERENCES personajes (id) ON DELETE CASCADE,
    orden         integer  NOT NULL CHECK (orden >= 1),
    texto         text     NOT NULL,
    PRIMARY KEY (personaje_id, orden)
);
CREATE TABLE familiares (                          -- sólo el que eligió familiar
    personaje_id    bigint   PRIMARY KEY REFERENCES personajes (id) ON DELETE CASCADE,
    tipo            smallint NOT NULL CHECK (tipo BETWEEN 1 AND 255),
    nombre          text     NOT NULL,
    nivel           smallint NOT NULL CHECK (nivel BETWEEN 0 AND 255),
    exp             bigint   NOT NULL,
    exp_para_subir  bigint   NOT NULL,
    vida            bigint   NOT NULL,
    vida_max        bigint   NOT NULL,
    golpe_min       bigint   NOT NULL,
    golpe_max       bigint   NOT NULL,
    muerto          boolean  NOT NULL,
    habilidad_1     integer  NOT NULL,
    habilidad_2     integer  NOT NULL,
    habilidad_3     integer  NOT NULL,
    habilidad_4     integer  NOT NULL
);


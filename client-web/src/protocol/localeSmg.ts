/**
 * One `strExtra` word. A leading sigil means "this is an index, resolve it to a name":
 * `*`=skill, `$`=NPC, `~`=charIndex, `^`=spell, `°`=object (modLocales.bas). No sigil = literal.
 */
function resolveArg(word: string, r: LocaleResolvers): string {
  if (!word) return word;
  const n = Number.parseInt(word.slice(1), 10);
  if (Number.isNaN(n)) return word;
  switch (word[0]) {
    case '~': return r.charName?.(n) ?? word.slice(1);
    case '^': return r.spellName?.(n) ?? word.slice(1);
    case '*': return r.skillName?.(n) ?? word.slice(1);
    case '$': return r.npcName?.(n) ?? word.slice(1);
    case '°': return r.itemName?.(n) ?? word.slice(1);
    default: return word;   // plain literal (a number, a player name, …)
  }
}

/**
 * Mirrors modLocales.bas `Locale_Parse_ServidorMensaje`: look the id up, split `strExtra` on `%`,
 * resolve each word's sigil, then substitute `#1`..`#4`. Unknown ids surface as `[loc N]` rather
 * than an empty string, so a wrong id is visible instead of silently blank.
 */
export function parseLocaleMsg(id: number, extra = '', r: LocaleResolvers = {}): string {
  // EL SIGILO `=` LE GANA AL ID, y va antes que nada. Significa "el mensaje es el PropioMsg del hechizo",
  // y el original devuelve ahí mismo sin llegar a mirar el catálogo (modLocales.bas:224). El server lo manda
  // con el id 0 —que no existe, la tabla arranca en 1— cada vez que te lanzás un hechizo a vos mismo, así que
  // mirando el id primero un mago leía `[loc 0]` en el chat cada vez que se curaba.
  for (const w of extra.split('%')) {
    if (w[0] !== '=') continue;
    const n = Number.parseInt(w.slice(1), 10);
    // Los hechizos ofensivos no tienen PropioMsg y el original tampoco escribe nada para ellos.
    return (Number.isNaN(n) ? undefined : r.spellSelfText?.(n)) ?? '';
  }
  let text = LOCALE_SMG[id];
  if (text === undefined) return `[loc ${id}]`;
  if (!extra) return text;
  const words = extra.split('%').map((w) => resolveArg(w, r));
  for (let n = 1; n <= 4; n++) text = text.split(`#${n}`).join(words[n - 1] ?? '');
  return text;
}
